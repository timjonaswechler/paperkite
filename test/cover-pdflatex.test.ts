import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { coverBuildFiles } from "../server/cover-mod.ts";
import {
  importManifest,
  type CoverModManifest,
} from "../server/cv-mod-prototype/model.ts";
import { dockerModBuilder } from "../server/cv-mod-prototype/native.ts";

test("pdfLaTeX cover glyphs match independent TeX reference, reject SS substitution and escape text safely", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "cover-glyphs-"));
  const config: CoverModManifest = {
    format: "bewerbung-cover-mod-v1",
    engine: "pdflatex",
    entrypoint: "layout/main.tex",
  };
  const layout = {
    "layout/main.tex": fs.readFileSync(
      "test/fixtures/cover-mod-pdflatex/main.tex",
    ),
  };
  const fields = {
    sender: "Sender",
    recipient: "Recipient",
    subject: "Subject",
    salutation: "Salutation",
    body: "Body",
    closing: "Mit freundlichen Grüßen. Straße, Fuß.",
  };
  const pdfImage = fs.readFileSync("pdf-tools/image-id", "utf8").trim();
  const builder = dockerModBuilder(
    fs.readFileSync("builder/image-id", "utf8").trim(),
    pdfImage,
  );
  try {
    assert.equal(importManifest(config).engine, "pdflatex");
    assert.throws(
      () => importManifest({ ...config, engine: "xelatex" }),
      /Manifest/,
    );
    assert.throws(
      () =>
        importManifest({
          ...config,
          format: "bewerbung-cv-mod-prototype-v1",
          fields: [],
        }),
      /LuaLaTeX/,
    );
    const actual = coverBuildFiles(config, layout, fields);
    assert.equal(actual["cv-data.lua"], undefined);
    const escaped = coverBuildFiles(config, layout, {
      ...fields,
      sender: "First\r\nSecond",
      body: "\\input{missing.tex} # $ % & _ ~ ^\n\nEnd",
    })["letter-data.tex"]!.toString();
    assert(
      escaped.includes("\\Lettersender{First\\hfil\\break\\null{}Second}"),
    );
    assert(escaped.includes("\\textbackslash{}input\\{missing.tex\\}"));
    assert(escaped.includes("\\par\\noindent{}End"));
    // Independently specified TeX, not generated by the encoder under test.
    const reference = {
      ...actual,
      "letter-data.tex": Buffer.from(String.raw`\long\def\Lettersender{Sender}
\long\def\Letterrecipient{Recipient}
\long\def\Lettersubject{Subject}
\long\def\Lettersalutation{Salutation}
\long\def\Letterbody{Body}
\long\def\Letterclosing{Mit freundlichen Gr\"u\ss{}en. Stra\ss{}e, Fu\ss{}.}
`),
    };
    const wrong = coverBuildFiles(config, layout, {
      ...fields,
      closing: "Mit freundlichen GrüSSen. StraSSe, FuSS.",
    });
    const rendered: Record<string, Buffer> = {};
    for (const [name, files] of Object.entries({ reference, wrong, actual })) {
      const input = path.join(root, name, "input"),
        output = path.join(root, name, "output");
      fs.mkdirSync(input, { recursive: true });
      fs.mkdirSync(output);
      for (const [file, bytes] of Object.entries(files)) {
        fs.mkdirSync(path.dirname(path.join(input, file)), { recursive: true });
        fs.writeFileSync(path.join(input, file), bytes);
      }
      const result = await builder(input, output, new AbortController().signal);
      assert.match(result.log, /This is pdfTeX/);
      if (name === "actual")
        assert.match(result.text, /Mit freundlichen Grüßen\. Straße, Fuß\./);
      rendered[name] = execFileSync(
        "docker",
        [
          "run",
          "--rm",
          "--network=none",
          "--read-only",
          "--cap-drop=ALL",
          "--security-opt=no-new-privileges",
          "--user",
          `${process.getuid!()}:${process.getgid!()}`,
          "--mount",
          `type=bind,src=${output},dst=/input,readonly`,
          "--entrypoint",
          "pdftoppm",
          pdfImage,
          "-f",
          "1",
          "-singlefile",
          "-r",
          "96",
          "/input/document.pdf",
        ],
        { maxBuffer: 8 * 1024 * 1024 },
      );
    }
    assert.notDeepEqual(
      rendered.wrong,
      rendered.reference,
      "negative control must detect visible SS instead of ß",
    );
    assert.deepEqual(
      rendered.actual,
      rendered.reference,
      "rendered ß must match the independent TeX glyph reference",
    );
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
